import type { ReportDiff } from "./diff.js";
import type { Explanation } from "./llm.js";
import type { Report, Violation, ViolationType } from "./types.js";

/** Hidden marker so the GitHub Action can find and update its own comment instead of posting a new one each push. */
export const COMMENT_MARKER = "<!-- archguard:pr-comment -->";

export interface CommentContext {
  /** e.g. "https://github.com/bytebyjay/shop" — enables clickable file links. */
  repoUrl?: string;
  /** Commit the head report was built from (links point here). */
  headSha?: string;
  /** Path from the repo root to the analysed folder ("" or "." for the root). */
  pathPrefix?: string;
  /** LLM explanations keyed by violation key. */
  explanations?: Map<string, Explanation>;
  /** Max items per list (default 20). */
  limit?: number;
}

const LABEL: Record<ViolationType, string> = {
  "circular-dependency": "Circular dependency",
  "layer-violation": "Layer violation",
  "god-file": "God file",
  "orphan-file": "Possibly unused file",
};

const PLURAL: Record<ViolationType, string> = {
  "circular-dependency": "Circular dependencies",
  "layer-violation": "Layer violations",
  "god-file": "God files",
  "orphan-file": "Possibly unused files",
};

const ICON = { error: "🔴", warning: "🟠", info: "⚪" } as const;

/**
 * Renders the pull-request comment. It focuses on what the PR CHANGED:
 * new problems first, then fixed ones, with the overall score for context.
 */
export function renderPrComment(base: Report, head: Report, diff: ReportDiff, ctx: CommentContext = {}): string {
  const limit = ctx.limit ?? 20;
  const link = linker(ctx);
  const lines: string[] = [COMMENT_MARKER, "## 🛡️ ArchGuard architecture check", ""];

  const d = diff.healthDelta;
  const arrow = d > 0 ? `▲ +${d}` : d < 0 ? `▼ ${d}` : "no change";
  lines.push(
    `**Health: ${base.score.health} → ${head.score.health}** (${arrow}) · grade ${base.score.grade} → ${head.score.grade}`,
    "",
  );

  const introducedErrors = diff.introduced.filter((v) => v.severity === "error").length;
  if (diff.introduced.length === 0) {
    lines.push("✅ **This PR introduces no new architecture issues.**", "");
  } else {
    lines.push(
      `⚠️ **This PR introduces ${diff.introduced.length} new issue${diff.introduced.length > 1 ? "s" : ""}**` +
        (introducedErrors ? ` (${introducedErrors} blocking)` : "") + ".",
      "",
    );
  }

  // Summary table
  const count = (r: Report, t: ViolationType) => r.summary.violations[t];
  const delta = (a: number, b: number) => (b > a ? ` (+${b - a})` : b < a ? ` (−${a - b})` : "");
  lines.push("| | Base | This PR |", "|---|---:|---:|");
  lines.push(`| Files | ${base.summary.files} | ${head.summary.files}${delta(base.summary.files, head.summary.files)} |`);
  for (const t of Object.keys(LABEL) as ViolationType[]) {
    lines.push(`| ${PLURAL[t]} | ${count(base, t)} | ${count(head, t)}${delta(count(base, t), count(head, t))} |`);
  }
  lines.push("");

  if (diff.introduced.length) {
    lines.push(`### New issues (${diff.introduced.length})`, "");
    const sorted = [...diff.introduced].sort(bySeverity);
    for (const v of sorted.slice(0, limit)) lines.push(...renderViolation(v, link, ctx.explanations?.get(v.key)));
    if (sorted.length > limit) lines.push(`_…and ${sorted.length - limit} more. Download the full report from the workflow run._`, "");
  }

  if (diff.resolved.length) {
    lines.push(`### Fixed in this PR (${diff.resolved.length}) 🎉`, "");
    for (const v of diff.resolved.slice(0, limit)) lines.push(`- ~~${LABEL[v.type]}~~: ${describe(v, link)}`);
    if (diff.resolved.length > limit) lines.push(`- _…and ${diff.resolved.length - limit} more_`);
    lines.push("");
  }

  lines.push(
    "<sub>Generated by ArchGuard v" + head.meta.version +
      ". Only issues this PR introduces are listed; existing issues are tracked in the score." +
      (ctx.explanations?.size ? " Explanations are AI-generated, so verify before acting." : "") +
      "</sub>",
  );
  return lines.join("\n");
}

/** Inline code that can't be broken out of: the fence is longer than any backtick run inside. */
export function code(text: string): string {
  const t = text.replace(/\s+/g, " ").trim();
  const longest = Math.max(0, ...(t.match(/`+/g) ?? []).map((m) => m.length));
  const fence = "`".repeat(longest + 1);
  return `${fence}${t.startsWith("`") || t.endsWith("`") ? ` ${t} ` : t}${fence}`;
}

/** Turns untrusted text into inert plain text: no links, images, HTML, mentions or markdown structure. */
export function plain(text: string): string {
  return text
    .replace(/\s+/g, " ")
    .replace(/[<>\[\]`*_~|\\]/g, (c) => `\\${c}`)
    .replace(/@/g, "@\u200b")
    .replace(/https?:\/\//gi, (m) => m.replace("://", "\u200b://"))
    .trim();
}

function renderViolation(v: Violation, link: Linker, explanation?: Explanation): string[] {
  const out = [`- ${ICON[v.severity]} **${LABEL[v.type]}**: ${describe(v, link)}`];
  if (explanation) {
    out.push("  <details><summary>💡 Why it matters and how to fix it</summary>", "");
    out.push(`  ${plain(explanation.explanation)}`, "");
    if (explanation.suggestion) out.push(`  **Suggested fix:** ${plain(explanation.suggestion)}`, "");
    out.push("  </details>");
  }
  return out;
}

function describe(v: Violation, link: Linker): string {
  switch (v.type) {
    case "circular-dependency": {
      const loop = v.message.split(": ").slice(1).join(": ");
      return loop.split(" -> ").map((f, i, all) => (i === all.length - 1 ? code(f) : link(f))).join(" → ");
    }
    case "layer-violation":
      return `${code(v.rule ?? "")}: ${link(v.file, v.line)} imports ${link(v.target!)}`;
    default:
      return `${link(v.file)} ${plain(v.message.replace(v.file, ""))}`;
  }
}

type Linker = (file: string, line?: number) => string;

function linker(ctx: CommentContext): Linker {
  const prefix = ctx.pathPrefix && ctx.pathPrefix !== "." ? `${ctx.pathPrefix.replace(/\/$/, "")}/` : "";
  return (file, line) => {
    const label = code(`${file}${line ? `:${line}` : ""}`);
    if (!ctx.repoUrl || !ctx.headSha) return label;
    const encoded = `${prefix}${file}`.split("/").map(encodeURIComponent).join("/");
    return `[${label}](${ctx.repoUrl}/blob/${ctx.headSha}/${encoded}${line ? `#L${line}` : ""})`;
  };
}

const RANK = { error: 0, warning: 1, info: 2 } as const;
const bySeverity = (a: Violation, b: Violation) => RANK[a.severity] - RANK[b.severity];
